def tool_code(wf: dict) -> dict:
    code = {"claimsDb": {"handler.py": CLAIMS_HANDLER, "requirements.txt": "", "events.json": CLAIMS_EVENTS}}
    for point, ic in wf["orchestrator"]["interceptors"].items():
        code[f"interceptor-{point}"] = interceptor_code.files(point, ic["templates"], wf)
    return code


def project(byo: bool = False) -> dict:
    wf = copy.deepcopy(WORKFLOW)
    name = "Demo: everything in one run"
    if byo:
        name += " (with a harness by ARN)"
        wf["agents"]["byoHarness"] = {
            "name": "Existing harness", "runtime": "harness",
            # REPLACE: the ARN of a harness you made elsewhere, in the deploy's account and region.
            "harness": {"arn": BYO_PLACEHOLDER, "maxIterations": 3, "timeoutSeconds": 120}}
        wf["steps"][2]["parallel"].append("byoHarness")
    return {"project": {"name": name, "workflow": wf, "prompts": copy.deepcopy(PROMPTS), "toolCode": tool_code(wf)}}


def bundle(body: dict) -> dict:
    """What the Build view's Import a file reads (web/src/builder/model.ts fromFile)."""
    p = body["project"]
    return {"format": "agentexpress-bundle", "version": 1,
            "framework": {"version": (ORCH / "VERSION").read_text().strip()},
            "project": {"id": "demo-everything", "name": p["name"], "exportedAt": "2025-01-01T00:00:00.000Z"},
            "workflow": p["workflow"], "prompts": p["prompts"], "toolCode": p["toolCode"]}


def outputs() -> dict[str, str]:
    dump = lambda d: json.dumps(d, indent=1, ensure_ascii=False) + "\n"  # noqa: E731 - a one-line local helper
    main, byo = project(), project(byo=True)
    return {"project.json": dump(main), "project.byo-harness.json": dump(byo),
            "bundle.json": dump(bundle(main)), "bundle.byo-harness.json": dump(bundle(byo))}


def main(argv: list[str]) -> int:
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print(f"out of date: {', '.join(stale)}. Run python3 examples/demo-everything/make_project.py",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
